import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { parseServerConfig } from "../src/config.js";
import { loadDiscoveryConfig } from "./discovery-config.js";
import {
  discoverMetadata,
  metadataFingerprint,
} from "../src/features/products/sankhya/metadata.js";
import { createOracleProductReader } from "../src/features/products/sankhya/session.js";
import { sankhyaMetadata } from "../src/features/products/sankhya/snapshot.js";
import { sankhyaCatalog } from "../src/features/products/sankhya/catalog.js";
import { metadataProblems } from "../src/features/products/sankhya/source.js";
import { format } from "prettier";
import { ProductFailure } from "../src/features/products/errors.js";

const runtimeCheck = process.argv.includes("--runtime-check");
const config = runtimeCheck
  ? parseServerConfig(process.env)
  : await loadDiscoveryConfig("sankhya");
if (config.environment === "production")
  throw new Error(
    "Discovery must run outside production application configuration",
  );
if (
  runtimeCheck &&
  (process.argv.includes("--write-reviewed") ||
    process.argv.includes("--check"))
)
  throw new Error(
    "Runtime verification cannot promote or compare the discovery snapshot",
  );
const reader = createOracleProductReader(
  config,
  runtimeCheck ? "runtime" : "discovery",
);
try {
  const snapshot = await reader.read(
    AbortSignal.timeout(45000),
    discoverMetadata,
  );
  const problems = metadataProblems(sankhyaCatalog, sankhyaMetadata, snapshot);
  if (runtimeCheck) {
    // ALL_* visibility is narrower for a reader. Only enabled dependencies
    // matter here; never promote a snapshot from that partial visibility.
    console.log(
      JSON.stringify({
        scope: "enabled runtime capabilities",
        problems,
        promoted: false,
      }),
    );
    if (problems.length) process.exitCode = 1;
  } else {
    const destination = resolve("evals/.local/sankhya");
    await mkdir(destination, { recursive: true });
    const generated = await format(
      `// Generated by products:sankhya:sync. Review before promotion; no automatic exposure.\nimport type { SankhyaMetadata } from "./metadata.js";\nexport const sankhyaMetadata: SankhyaMetadata = ${JSON.stringify(snapshot)};\n`,
      { parser: "typescript" },
    );
    await writeFile(
      resolve(destination, "metadata-candidate.ts.txt"),
      generated,
    );
    await writeFile(
      resolve(destination, "metadata-candidate.json"),
      JSON.stringify(snapshot, null, 2),
    );
    const changed =
      metadataFingerprint(snapshot) !== metadataFingerprint(sankhyaMetadata);
    if (process.argv.includes("--write-reviewed")) {
      if (problems.length)
        throw new Error(
          "Used metadata changed; update and validate the catalog before promotion",
        );
      await writeFile(
        resolve("src/features/products/sankhya/snapshot.ts"),
        generated,
      );
    }
    console.log(
      JSON.stringify({
        tables: snapshot.tables.length,
        columns: snapshot.tables.reduce((n, t) => n + t.columns.length, 0),
        dictionaryLinks: snapshot.links.length,
        changed,
        problems,
        candidate: "evals/.local/sankhya/metadata-candidate.ts.txt",
        promoted: process.argv.includes("--write-reviewed"),
      }),
    );
    if (problems.length || (changed && process.argv.includes("--check")))
      process.exitCode = 1;
  }
} catch (cause) {
  const refused =
    runtimeCheck &&
    cause instanceof ProductFailure &&
    cause.cause instanceof Error &&
    cause.cause.message === "A SELECT-only non-owner ERP account is required";
  console.error(
    refused
      ? "Sankhya runtime verification refused the configured account; use a SELECT-only non-owner reader (PH-08)."
      : "Sankhya read-only synchronization failed; no catalog was promoted.",
  );
  process.exitCode = 1;
} finally {
  try {
    await reader.close();
  } catch {
    console.error("Sankhya reader cleanup failed.");
    process.exitCode = 1;
  }
}
